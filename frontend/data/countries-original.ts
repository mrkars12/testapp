// دالة مساعدة للبحث عن الدولة بالاسم أو الكود
export function findCountryByName(
  name: string | null | undefined
): Country | undefined {
  if (!name) return undefined
  return countries.find(c =>
    c.name === name || c.name_ar === name || c.code === name
  )
}



// دالة للحصول على كود الدولة
export function getCountryCode(countryName: string): string {
  const country = findCountryByName(countryName)
  return country ? country.code : ''
}

export function getDialCode(countryName: string): string {
  const country = findCountryByName(countryName)
  return country ? country.dial_code : ''
}

export function getArabicName(countryName: string): string {
  const country = findCountryByName(countryName)
  return country ? country.name_ar : countryName
}

export function getSortedCountries(): Country[] {
  return [...countries].sort((a, b) =>
    a.name_ar.localeCompare(b.name_ar, 'ar')
  )
}
